#!/usr/bin/env python3
"""Point the legacy dashboards and root short links at the canonical site.

Run from the repository root:

    python3 scripts/build_legacy_redirects.py

Why this exists
---------------
`main` still holds the dashboards that earlier parallel sessions published (`docs/`,
`planner/`, `verified/`). The GitHub Pages source for this repository is the legacy
`main /` setting, and the repository token cannot change it (`PUT /pages` returns 403),
so every file in the repository root is served at https://karagemop466-tech.github.io/Poker3/.

Those directories therefore publish a second, older set of conclusions at the same host:
`docs/` still says hotel rates and walking times are unverified, while the canonical
`site/` publishes the dated rate log. Leaving both reachable is how the user ends up
reading a page the dashboard contradicts.

The same dual-publisher race has a second symptom. When the Actions artifact wins, it
publishes `site/` at the host root, so `/Poker3/calculator.html` exists; when the legacy
branch build wins, only the repository root exists, and that same path 404s unless a
root-level file exists. An independent live read on 2026-11-19 found exactly that split
(calculator and venue subpages 404 at the root while `/Poker3/site/...` served them).
This script now also generates a root-level redirect for every canonical
`site/**/*.html` path that has no root counterpart, so both publishers resolve every
internal link.

This script does not delete them and does not edit their data. It rewrites each legacy
page into a redirect to the canonical page that carries the same subject, so an old
bookmark lands on the current evidence instead of a stale table. Every original file
stays in git history.

The canonical dashboard is `site/`. The repository root files that were already
redirects before this script existed are left untouched.
"""
from __future__ import annotations

import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
SITE = ROOT / "site"

# Legacy page -> canonical subject page. Anything unmapped falls back to site/index.html.
LEGACY_DIRECTORIES = {
    "docs": {
        "index.html": "site/index.html",
        "summary.html": "site/index.html",
        "tournaments.html": "site/tournaments.html",
        "multi-entry.html": "site/browse.html?view=category&key=extra",
        "schedule.html": "site/schedule.html",
        "hotels.html": "site/hotels.html",
        "questions.html": "site/questions.html",
        "suggestions.html": "site/suggestions.html",
        "flagged.html": "site/flagged.html",
        "sources.html": "site/sources.html",
    },
    "planner": {
        "index.html": "site/index.html",
        "executive-summary.html": "site/index.html",
        "tournaments.html": "site/tournaments.html",
        "schedule.html": "site/schedule.html",
        "hotels.html": "site/hotels.html",
        "suggestions.html": "site/suggestions.html",
        "q-and-a.html": "site/questions.html",
        "flagged-for-review.html": "site/flagged.html",
    },
    "verified": {
        "index.html": "site/index.html",
        "summary.html": "site/index.html",
        "best-picks.html": "site/index.html",
        "tournaments-single.html": "site/tournaments.html",
        "tournaments-multi.html": "site/browse.html?view=category&key=extra",
        "schedule.html": "site/schedule.html",
        "hotels.html": "site/hotels.html",
        "questions.html": "site/questions.html",
        "suggestions.html": "site/suggestions.html",
        "flagged.html": "site/flagged.html",
        "sources.html": "site/sources.html",
        "repo-review.html": "site/flagged.html",
    },
}

TEMPLATE = """<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width,initial-scale=1">
<meta name="robots" content="noindex">
<title>Moved to the Vegas Poker Planner</title>
<!--
  {reason}

  The repository's GitHub Pages source is the legacy "main /" setting, while the
  Actions workflow also publishes the site/ artifact. This path is therefore served
  from the repository root when the legacy publisher wins, and from the artifact when
  the Actions publisher wins. Redirecting keeps either publisher on the canonical
  evidence instead of a stale table or a 404.

  Canonical target: {target}
  Generated by: scripts/build_legacy_redirects.py
-->
<link rel="canonical" href="{canonical}">
<meta http-equiv="refresh" content="0; url={url}">
<style>
  :root{{color-scheme:dark light}}
  body{{margin:0;min-height:100vh;display:grid;place-items:center;background:#0d1117;color:#e6edf3;
       font:16px/1.6 -apple-system,BlinkMacSystemFont,"Segoe UI",Roboto,Helvetica,Arial,sans-serif;padding:24px}}
  main{{max-width:34rem;text-align:center}}
  h1{{font-size:1.25rem;margin:0 0 .5rem;font-weight:650}}
  p{{margin:.5rem 0;color:#9aa7b4}} a{{color:#6ea8fe}}
</style>
</head>
<body>
<main>
  <h1>{heading}</h1>
  <p>{lead} If nothing happens,
     <a href="{url}">open it here</a>.</p>
  <p>It carries every tournament, fee, guarantee and hotel term with the official page
     the value was read from.</p>
</main>
<script>location.replace({js});</script>
</body>
</html>
"""

LEGACY_REASON = (
    "Retired dashboard page. It was published by an earlier session on a separate branch "
    "and is kept in git history, not republished here."
)
ROOT_REASON = (
    "Root-level compatibility redirect. The canonical dashboard lives in site/; when the "
    "legacy branch publisher wins, this path must redirect there rather than 404."
)


def depth_prefix() -> str:
    return "../"


def render(path: pathlib.Path, target: str, url: str, reason: str, heading: str, lead: str) -> None:
    """Write one static redirect, preserving a query string in location.replace."""
    # The canonical link must be relative to the redirect file itself, not to the
    # repository root: a nested short link lives in venues/ or poker3/.
    canonical = url.split("?")[0].split("#")[0]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        TEMPLATE.format(
            target=target, canonical=canonical, url=url, reason=reason,
            heading=heading, lead=lead, js="'" + url + "' + location.hash",
        ),
        encoding="utf-8",
    )


def main() -> int:
    written = 0
    for directory, mapping in LEGACY_DIRECTORIES.items():
        base = ROOT / directory
        if not base.is_dir():
            continue
        for old, target in mapping.items():
            path = base / old
            if not path.exists():
                print(f"skip (missing): {directory}/{old}")
                continue
            url = depth_prefix() + target
            # A query string survives location.replace; the meta refresh keeps a
            # no-JavaScript visitor moving too. The canonical link is relative to
            # this legacy page, so it must carry the same ../ prefix as url.
            canonical = url.split("?")[0].split("#")[0]
            path.write_text(
                TEMPLATE.format(
                    target=target, canonical=canonical, url=url, reason=LEGACY_REASON,
                    heading="This dashboard has been retired",
                    lead="The current, source-linked dashboard is loading.",
                    js="'" + url + "' + location.hash",
                ),
                encoding="utf-8",
            )
            written += 1

    # Root-level counterparts for canonical pages. The Actions artifact publishes
    # site/ at the host root, so these files are not in that artifact; they matter
    # only when the legacy branch publisher wins. Existing root redirects are kept
    # as they are, so earlier sessions' comments and targets are preserved.
    root_written = 0
    for canonical_path in sorted(SITE.glob("**/*.html")):
        rel = canonical_path.relative_to(SITE)
        root_path = ROOT / rel
        if root_path.exists():
            continue
        depth = len(rel.parts) - 1
        url = ("../" * depth) + "site/" + rel.as_posix()
        target = "site/" + rel.as_posix()
        render(
            root_path, target, url, ROOT_REASON,
            "Opening the current dashboard",
            "The canonical page is loading.",
        )
        root_written += 1

    print(f"rewrote {written} legacy pages as redirects to site/")
    print(f"generated {root_written} root-level compatibility redirects")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
