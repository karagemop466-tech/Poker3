#!/usr/bin/env python3
"""Convert this session's fresh 2026-11-19 DSE IV capture into the canonical capture
format and verify it against site/data.json.

The fresh capture (`raw/dse_schedule_live_2026-11-19_4475a074.md`) keeps the page's own
column order (Date, Time, Event #, Event Name, Structures). `scripts/verify_dse_live_2026_11_19.py`
expects (row#, date, time, event#, name, sheet#). This script normalises the fresh read into
that format and runs the same field-by-field comparison, so this session's independent read
guards the published catalog the same way the primary capture does.

Run from the repository root:

    python3 scripts/verify_fresh_4475a074.py
"""
from __future__ import annotations

import datetime as dt
import json
import pathlib
import re
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
FRESH = ROOT / "raw" / "dse_schedule_live_2026-11-19_4475a074.md"
CANONICAL = ROOT / "raw" / "dse_schedule_live_2026-11-19_4475a074_canonical.md"
ROW = re.compile(
    r"^\|\s*([A-Z][a-z]+, [A-Z][a-z]+ \d{1,2}, \d{4})\s*\|\s*([^|]+?)\s*\|\s*(\d+)\s*\|"
    r"\s*([^|]+?)\s*\|\s*structure_(\d+)\.pdf\s*\|\s*$"
)


def main() -> int:
    rows = []
    for line in FRESH.read_text(encoding="utf-8").splitlines():
        m = ROW.match(line.strip())
        if not m:
            continue
        date_text, time, number, name, sheet = m.groups()
        iso = dt.datetime.strptime(date_text, "%A, %B %d, %Y").strftime("%Y-%m-%d")
        rows.append((len(rows) + 1, iso, time.strip(), int(number), name.strip(), int(sheet)))

    if len(rows) != 94:
        print(f"FAIL: fresh capture parsed {len(rows)} rows, expected 94")
        return 1

    with CANONICAL.open("w", encoding="utf-8") as fh:
        fh.write(
            "# Canonicalised fresh 2026-11-19 capture for the DSE IV verifier "
            "(session arena/4475a074-poker3).\n\n"
            "Generated by scripts/verify_fresh_4475a074.py from "
            "raw/dse_schedule_live_2026-11-19_4475a074.md.\n\n"
        )
        for n, iso, time, number, name, sheet in rows:
            fh.write(f"| {n} | {iso} | {time} | {number} | {name} | {sheet} |\n")
    print(f"parsed {len(rows)} fresh rows into {CANONICAL.relative_to(ROOT)}")

    # Run the canonical verifier against this capture.
    proc = subprocess.run(
        [sys.executable, str(ROOT / "scripts" / "verify_dse_live_2026_11_19.py"),
         str(CANONICAL)],
        capture_output=True, text=True,
    )
    sys.stdout.write(proc.stdout)
    sys.stderr.write(proc.stderr)
    return proc.returncode


if __name__ == "__main__":
    sys.exit(main())
