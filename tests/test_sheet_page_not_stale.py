#!/usr/bin/env python3
"""Regression guards for the stale-source defect fixed on 2026-11-17 (flag F68).

`site/sheets.html` is a page in the site navigation. It used to be generated by
`scripts/build_addendum.py` from `site/data/{tournaments,hotels,routes,flags}.json`,
four files frozen on 2026-11-16 that no script regenerated. The page therefore
published 14 retired `FL`-prefixed flags instead of the live 72-item `F` register,
5 of the 8 hotels, and 13 of the 15 walking routes with every walking time blank.

These tests fail if that comes back, in either of the two ways it could:
  * someone restores a stale `site/data/*.json` snapshot, or
  * the generator goes back to reading one.
"""
from __future__ import annotations

import json
import re
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DATA = json.loads((ROOT / "site" / "data.json").read_text(encoding="utf-8"))
SHEETS = (ROOT / "site" / "sheets.html").read_text(encoding="utf-8")
BUILDER = (ROOT / "scripts" / "build_addendum.py").read_text(encoding="utf-8")

# The retired 2026-11-16 snapshots. site/data.json is the only current data file.
STALE_FILES = ["hotels.json", "rates.json", "routes.json", "flags.json",
               "tournaments.json", "questions.json", "suggestions.json", "sources.json"]


class NoStaleSnapshotFiles(unittest.TestCase):
    def test_retired_snapshot_files_are_gone(self):
        for name in ("hotels.json", "rates.json", "routes.json"):
            self.assertFalse(
                (ROOT / "site" / "data" / name).exists(),
                f"site/data/{name} was retired with flag F68; restoring it revives stale data",
            )

    def test_generator_does_not_read_a_snapshot_json(self):
        """build_addendum.py may read site/data.json and the data modules, nothing else."""
        for m in re.finditer(r"""load\(\s*["']?([^"')]+)""", BUILDER):
            target = m.group(1)
            self.assertNotIn(
                "data/", target.replace("site/data.json", ""),
                f"build_addendum.py reads {target!r}; it must read site/data.json only",
            )
        for stale in ("hotels.json", "rates.json", "routes.json", "flags.json"):
            self.assertNotIn(
                f'"{stale}"', BUILDER,
                f"build_addendum.py still names {stale}, a retired snapshot",
            )


class SheetsPageMatchesCanonicalData(unittest.TestCase):
    """The rendered page must carry the same counts as site/data.json."""

    def test_every_flag_is_rendered(self):
        rendered = set(re.findall(r'id="fl-(F\d+)"', SHEETS))
        expected = {f["id"] for f in DATA["flags"]}
        self.assertEqual(expected - rendered, set(), "flags in data.json missing from sheets.html")

    def test_no_retired_fl_prefix_survives(self):
        self.assertNotRegex(
            SHEETS, r"\bFL\d\d\b",
            "a retired FL-prefixed flag is on the page; the live register uses F-prefixed ids",
        )

    def test_every_hotel_is_rendered(self):
        import html as _html
        rendered = _html.unescape(SHEETS)
        for hotel in DATA["hotels"]:
            self.assertIn(hotel["name"], rendered, f"hotel missing from sheets.html: {hotel['name']}")

    def test_no_route_has_a_blank_walking_time(self):
        """data.json carries a minutes figure for every route; the page must not print 'blank'."""
        self.assertTrue(all(r.get("minutes") not in (None, "") for r in DATA["routes"]))
        routes_section = SHEETS.split("Hotel–venue walking routes", 1)[-1]
        self.assertNotIn(">blank<", routes_section,
                         "a walking time rendered blank; site/data.json has one for every route")

    def test_read_record_and_module_agree_on_every_sheet(self):
        """The page states this cross-check; assert it here so the claim cannot go stale."""
        self.assertIn("Cross-check passed at build time", SHEETS,
                      "the build-time sheet cross-check no longer passes or is not reported")

    def test_sheet_matrix_has_no_empty_start_time_or_event_list(self):
        """Sheet 1-37 rows must carry their start time and event numbers, not a blank cell."""
        matrix = SHEETS.split("DeepStack Extravaganza IV sheets", 1)[1].split("<h2>", 1)[0]
        self.assertNotIn("<td></td>", matrix, "an empty cell in the sheet matrix")

    def test_all_52_structure_sheets_are_rendered(self):
        self.assertEqual(len(DATA["structureSheets"]), 52)
        self.assertIn("37 DeepStack Extravaganza IV sheets", SHEETS)
        self.assertIn("15 DeepStack Extravaganza NYE sheets", SHEETS)


if __name__ == "__main__":
    unittest.main(verbosity=2)
