# Per-event guarantee overrides where the sheet splits the guarantee by event
# number (sheet 7 and sheet 11).
GUARANTEE_OVERRIDE = {
    14: (30000, "$30,000"),
    28: (40000, "$40,000"),
    63: (30000, "$30,000"),
    16: (30000, "$30,000 (prize pool + total bounties)"),
    30: (40000, "$40,000 (prize pool + total bounties)"),
    54: (50000, "$50,000 (prize pool + total bounties)"),
}


def parse_guarantee(sheet_no, event_no):
    """Return (numeric guarantee or None, display string)."""
    if event_no in GUARANTEE_OVERRIDE:
        return GUARANTEE_OVERRIDE[event_no]
    raw = SHEETS[sheet_no]["guarantee"]
    if not raw:
        return None, ""
    digits = raw.replace(",", "").split("$")[-1].split(" ")[0]
    try:
        return int(digits), raw
    except ValueError:
        return None, raw


def build_events():
    """Turn SCHEDULE + SHEETS into the row records the site renders."""
    months = {11: "November", 12: "December"}
    rows = []
    for month, day, event_no, flight, name, start, reg_close, sheet_no in SCHEDULE:
        sh = SHEETS[sheet_no]
        gnum, gdisp = parse_guarantee(sheet_no, event_no)

        is_satellite = event_no in SATELLITE_EVENTS
        is_continuation = any(k in name for k in CONTINUATION_KEYWORDS)
        is_multifl = sh["reEntry"] == "multi-flight"

        if is_satellite:
            bucket = "satellite"
            entry_type = "Satellite"
        elif is_continuation:
            bucket = "continuation"
            entry_type = "Continuation day"
        elif is_multifl:
            bucket = "multi-entry"
            entry_type = "Multi-flight"
